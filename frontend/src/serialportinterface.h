    uint8_t crc8_calc(uint8_t *data, uint8_t length) {
        uint8_t crc = 0x00;
        for (uint8_t i = 0; i < length; i++) {
            crc = crc8_table[crc ^ data[i]];
        }
        return crc;
    }
